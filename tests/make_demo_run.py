#!/usr/bin/env python3
"""Generate a clearly-labelled DEMO run so the dashboard can be exercised before the
first real crawl. Titles are synthetic; the shop is literally named DEMO SHOP.
Never import this into the production database without realising that."""
import json, random
from pathlib import Path

OUT = Path("/home/pc/etsy-scraper/tests/fixtures/demo_run")
OUT.mkdir(parents=True, exist_ok=True)
random.seed(7)

STYLES = ["Vintage Sun", "Retro Mountain", "Cottagecore Frog", "Minimal Line Art",
          "Groovy Checkerboard", "Sarcastic Cat", "Born In The 90s", "Plant Mom"]
SHOPS = ["DEMO SHOP", "DemoThreads", "FixtureStudio"]
RUN = "demo-0001"

rows = []
for i, style in enumerate(STYLES):
    for kw, page in (("t-shirt", 1 + i // 4),):
        lid = str(100000 + i)
        price = round(random.uniform(16, 34), 2)
        on_sale = i % 3 == 0
        rows.append({
            "run_id": RUN, "keyword": kw, "page": page, "position": i + 1,
            "listing_id": lid, "url": f"https://www.etsy.com/listing/{lid}/demo",
            "captured_at": "2026-11-03T12:00:00+00:00",
            "title": f"{style} Tee — DEMO DATA",
            "price_usd": price,
            "price_original_usd": round(price * 1.3, 2) if on_sale else None,
            "price_min_usd": None, "price_max_usd": None,
            "is_on_sale": on_sale, "is_range": i % 4 == 0, "currency": "USD",
            "favorites": random.randint(40, 9800),
            "listing_review_count": random.randint(0, 1800),
            "listing_rating": round(random.uniform(4.3, 5.0), 1),
            "shop_review_count": random.randint(300, 40000),
            "shop_rating": round(random.uniform(4.5, 5.0), 1),
            "shop_name": SHOPS[i % len(SHOPS)], "shop_url": "https://www.etsy.com/shop/demo",
            "is_bestseller": i % 3 == 0, "is_star_seller": i % 2 == 0,
            "free_shipping": i % 2 == 1, "variation_count": random.randint(1, 24),
            "images_count": random.randint(3, 10),
            "thumbnail_url": None,
            "description": (f"{style} tee.\n\nDEMO DATA — not scraped from Etsy.\n"
                            "Soft cotton, unisex fit. Ships in 3-5 days."),
            "description_html": f"<p>{style} tee.</p>",
            "description_chars": 90,
            "raw_payload_path": None,
            "extraction": {"jsonld": True, "embedded": False, "dom": True, "warnings": []},
        })

# a second snapshot for three listings so price history has something to draw
for r in rows[:3]:
    h = dict(r)
    h["run_id"] = "demo-0002"
    h["captured_at"] = "2026-11-03T13:00:00+00:00"
    h["price_usd"] = round(r["price_usd"] * 0.85, 2)
    rows.append(h)

with (OUT / "results.jsonl").open("w") as fh:
    for r in rows:
        fh.write(json.dumps(r) + "\n")

(OUT / "run.json").write_text(json.dumps({
    "run_id": RUN, "keyword": "t-shirt", "depth": 20, "status": "succeeded",
    "started_at": "2026-11-03T11:58:00+00:00", "finished_at": "2026-11-03T12:00:00+00:00",
    "pages_done": 2, "occurrences": len(rows), "unique_listings": len(STYLES),
    "challenges": 0, "fixture": True,
    "note": "SYNTHETIC DEMO DATA — generated by tests/make_demo_run.py",
}, indent=1))

print(f"wrote {len(rows)} rows to {OUT}")
